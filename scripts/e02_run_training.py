"""Run the 30 E-02 trainings locally (plan: prereg/e02_balanced_view_plan.md). The registration status is a
required argument and is written to the run log: the OSF URL, or "unregistered: <reason>" when training starts
before registration (OSF was unavailable for scheduled maintenance from 16 to 19 October 2026).

Order: seed -> fold -> arm. Each run calls outputs/e02/runtime/e02_train.py (generated by scripts/e02_make_runtime.py)
with SKIN31_ROOT=data/e02/fold{f}/{ARM}, TRAINING_SEED=seed, FINAL_GROUP=b0,
E02_ONLY_EXP=FINAL_B0_Training_Optimization and MPLBACKEND=Agg. The script writes to <drive>:/kaggle/working/seed{seed};
its files are moved to outputs/e02/runs/{ARM}/fold{f}/seed{seed}/attempt{k}/. A run counts as done when its summary
status is "ok" and the final-epoch checkpoint exists. A run that fails for a technical reason (for example a
data-loader worker that cannot start) is restarted with the same seed, up to three attempts; nothing is deleted.
Usage (datn environment):
  python scripts/e02_run_training.py --registration https://osf.io/xxxxx
  python scripts/e02_run_training.py --registration "unregistered: OSF maintenance 16-19 Oct 2026"
"""
import argparse
import csv
import hashlib
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = ROOT / "outputs" / "e02" / "runtime"
RUNS = ROOT / "outputs" / "e02" / "runs"
DATA = ROOT / "data" / "e02"
SEEDS, FOLDS, ARMS = [42, 123, 2024], range(5), ["COUPLED", "BALANCED"]
CKPT = "final_b0_training_optimization_final.pth"
MAX_ATTEMPTS = 3
LOG = RUNS / "run_log.csv"


def work_dir(seed):
    return Path(RUNTIME.anchor) / "kaggle" / "working" / f"seed{seed}"


def ok(attempt_dir):
    s = attempt_dir / "experiment_summary.csv"
    return (attempt_dir / CKPT).exists() and s.exists() and pd.read_csv(s).status.iloc[0] == "ok"


def done(run_dir):
    return any(ok(a) for a in sorted(run_dir.glob("attempt*")))


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--registration", required=True,
                    help='OSF registration URL, or "unregistered: <reason>" if training starts before registration')
    args = ap.parse_args()
    reg = args.registration.strip()
    assert reg.startswith("https://osf.io/") or (reg.startswith("unregistered:") and len(reg) > 20), reg
    RUNS.mkdir(parents=True, exist_ok=True)
    new_log = not LOG.exists()
    with open(LOG, "a", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        if new_log:
            w.writerow(["time", "registration", "arm", "fold", "seed", "attempt", "returncode", "ok", "seconds",
                        "ckpt_sha256"])
        for seed in SEEDS:
            for f in FOLDS:
                for arm in ARMS:
                    run_dir = RUNS / arm / f"fold{f}" / f"seed{seed}"
                    if done(run_dir):
                        continue
                    for attempt in range(len(list(run_dir.glob("attempt*"))) + 1, MAX_ATTEMPTS + 1):
                        wd = work_dir(seed)
                        if wd.exists():  # leftovers of an interrupted run are kept, not deleted
                            shutil.move(str(wd), str(RUNS / "_stale" / f"{arm}_fold{f}_seed{seed}_{int(time.time())}"))
                        att = run_dir / f"attempt{attempt}"
                        att.mkdir(parents=True, exist_ok=True)
                        env = dict(os.environ, SKIN31_ROOT=str(DATA / f"fold{f}" / arm), TRAINING_SEED=str(seed),
                                   FINAL_GROUP="b0", E02_ONLY_EXP="FINAL_B0_Training_Optimization",
                                   MPLBACKEND="Agg", PYTHONWARNINGS="ignore")
                        t0 = time.time()
                        with open(att / "train_log.txt", "w", encoding="utf-8") as log:
                            rc = subprocess.run([sys.executable, "e02_train.py"], cwd=RUNTIME, env=env,
                                                stdout=log, stderr=subprocess.STDOUT).returncode
                        if wd.exists():
                            for p in list(wd.iterdir()):
                                shutil.move(str(p), str(att / p.name))
                        good = ok(att)
                        w.writerow([time.strftime("%Y-%m-%d %H:%M:%S"), reg, arm, f, seed, attempt, rc, good,
                                    round(time.time() - t0), sha256(att / CKPT) if good else ""])
                        fh.flush()
                        print(f"{arm} fold{f} seed{seed} attempt{attempt}: {'ok' if good else 'FAILED'} "
                              f"({round(time.time() - t0)} s)", flush=True)
                        if good:
                            break
                    else:
                        print(f"{arm} fold{f} seed{seed}: failed after {MAX_ATTEMPTS} attempts; stopping", flush=True)
                        return
    print("all runs done")


if __name__ == "__main__":
    main()
