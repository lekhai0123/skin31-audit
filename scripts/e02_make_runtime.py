"""Build the local E-02 training script from the released portable training notebook (code release v1.0.0).

The training functions of the portable notebook are identical to those of the notebook used for the benchmark
models (checked definition by definition; only build_model and run_experiment differ, by input checks that do not
affect EfficientNet-B0 without distillation), and so are the recipe constants and the B0 training-optimisation
configuration.

Changes made here, each checked to apply exactly once; nothing else is altered:
 1. The shell line `!pip -q install timm==1.0.26` is dropped (the local environment already has timm 1.0.26).
 2. `display` (an IPython built-in used only to print tables) is defined as `print`.
 3. After the cell that defines `experiments`, the list is filtered to the experiment named in E02_ONLY_EXP.
 4. The two flip views, written as `transforms.Lambda(lambda x: TF.vflip(x))` and `... TF.hflip(x)`, use named
    module-level functions with the same body, because Windows data-loader worker processes cannot receive lambdas.
 5. Windows data-loader workers re-import the script, so module-level statements other than imports and function or
    class definitions are placed, in their original order, under `if __name__ == "__main__":`. The release-package
    import (skin_disease) and its sys.path setup are guarded too. Function and class bodies are unchanged.
Runs set MPLBACKEND=Agg so that the preview figure of the notebook does not open a window.
Output: outputs/e02/runtime/e02_train.py and a copy of code/skin_disease next to it.
"""
import ast
import builtins
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NB = ROOT / "final_submission" / "skin31-audit" / "notebooks" / "training_kaggle_portable.ipynb"
CODE = ROOT / "final_submission" / "skin31-audit" / "code" / "skin_disease"
OUT = ROOT / "outputs" / "e02" / "runtime"

FILTER = (
    '\n_e02_only = os.environ.get("E02_ONLY_EXP")\n'
    'if _e02_only:\n'
    '    experiments = [e for e in experiments if e["exp_name"] == _e02_only]\n'
    '    assert len(experiments) == 1, _e02_only\n'
)
FLIPS = [("transforms.Lambda(lambda x: TF.vflip(x))", "transforms.Lambda(_e02_vflip)"),
         ("transforms.Lambda(lambda x: TF.hflip(x))", "transforms.Lambda(_e02_hflip)")]
FLIP_DEFS = ("def _e02_vflip(x):\n    return TF.vflip(x)\n\n\n"
             "def _e02_hflip(x):\n    return TF.hflip(x)\n")


def main():
    nb = json.load(open(NB, encoding="utf-8"))
    cells = ["".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code"]

    # 1. shell line
    shell = [l for c in cells for l in c.splitlines() if l.lstrip().startswith(("!", "%"))]
    assert shell == ["!pip -q install timm==1.0.26"], shell
    cells = ["\n".join(l for l in c.splitlines() if not l.lstrip().startswith(("!", "%"))) for c in cells]

    # 3. experiment filter after the cell that defines `experiments`
    hit = [i for i, c in enumerate(cells) if 'FINAL_GROUP = os.environ.get("FINAL_GROUP", "b0")' in c]
    assert len(hit) == 1, hit
    cells[hit[0]] += "\n" + FILTER

    # 4. flip lambdas -> named functions (inserted right before the cell that uses them)
    joined = "\n".join(cells)
    for old, _ in FLIPS:
        assert joined.count(old) == 1, old
    flip_cell = [i for i, c in enumerate(cells) if FLIPS[0][0] in c]
    assert len(flip_cell) == 1
    for old, new in FLIPS:
        cells[flip_cell[0]] = cells[flip_cell[0]].replace(old, new)
    cells.insert(flip_cell[0], FLIP_DEFS)

    # 5. guard module-level statements, keep order
    out = ['"""Generated by scripts/e02_make_runtime.py from notebooks/training_kaggle_portable.ipynb '
           '(code release v1.0.0). Do not edit by hand."""', "", "display = print", ""]
    defined = set(dir(builtins)) | {"display"}
    guarded_names = set()
    for k, src in enumerate(cells):
        if not src.strip():
            continue
        tree = ast.parse(src)
        lines = src.splitlines()
        for node in tree.body:
            start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
            seg = "\n".join(lines[start - 1:node.end_lineno])
            is_pkg_import = isinstance(node, ast.ImportFrom) and (node.module or "").startswith("skin_disease")
            if isinstance(node, (ast.Import, ast.ImportFrom)) and not is_pkg_import:
                out.append(seg)
                for a in node.names:
                    defined.add((a.asname or a.name).split(".")[0])
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                # names evaluated at definition time must exist in worker processes as well
                at_def = list(getattr(node, "decorator_list", []))
                if isinstance(node, ast.ClassDef):
                    at_def += node.bases + [s for s in node.body
                                            if not isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef))]
                else:
                    at_def += node.args.defaults + [d for d in node.args.kw_defaults if d is not None]
                used = {n.id for e in at_def for n in ast.walk(e) if isinstance(n, ast.Name)}
                bad = used - defined
                assert not bad, (node.name, bad)
                out.append(seg)
                defined.add(node.name)
            else:
                out.append('if __name__ == "__main__":')
                out.extend("    " + l if l.strip() else "" for l in seg.splitlines())
                for n in ast.walk(node):
                    if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store):
                        guarded_names.add(n.id)
            out.append("")
    script = "\n".join(out) + "\n"
    ast.parse(script)  # must be valid Python
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "e02_train.py").write_text(script, encoding="utf-8")
    if (OUT / "code").exists():
        shutil.rmtree(OUT / "code")
    shutil.copytree(CODE, OUT / "code" / "skin_disease", ignore=shutil.ignore_patterns("__pycache__"))
    print("written", OUT / "e02_train.py", f"({len(script.splitlines())} lines)")


if __name__ == "__main__":
    main()
